"""Approximate message passing (AMP) for the teacher-student kinetic Ising model.

Teacher
-------
The disordered kinetic Ising model of Zavatone-Veth & Pehlevan (2026),
https://doi.org/10.1088/1751-8121/ae38a4, as implemented in simulate.py:

    p(s_t | s_{t-1..t-K}) = prod_i sigmoid(2 beta s_t,i h_t,i),
    h_t,i = sum_{lag=1}^K sum_j J_{ij,lag} s_{t-lag,j},
    J_{ij,:} ~ N(0, Gamma / N) iid over (i, j), correlated across lags by Gamma.

The student observes one or more trajectories generated by the teacher and
infers J. Given the full trajectory the likelihood factorizes over rows i
(the dynamics are causal, so later spins never feed back into the
conditional of earlier ones), and the prior factorizes over (i, j), so the
posterior over J is a product over rows: N independent generalized linear
models sharing the same design matrix.

Mapping onto the multi-class AMP
--------------------------------
For a fixed row i, let

    w_j  = J_{ij,:}                         in R^K   (one K-vector per neighbour j)
    x_tj = (s_{t-1,j}, ..., s_{t-K,j})      in R^K
    y_t  = s_t,i                            in {-1, +1}

so that h_t = sum_j w_j . x_tj. This is the setting of Algorithm 1 in
Cornacchia et al., "Learning curves for the multi-class teacher-student
perceptron" (2023), https://doi.org/10.1088/2632-2153/acb428 (appendix E),
with roles of the indices adapted: there every feature j carries a k-vector
weight w_j (one entry per class) multiplying a scalar input; here every
neighbour j carries a K-vector weight (one entry per lag) multiplying a
K-vector input. In both cases the posterior means w_hat_j are vectors and
their variances C_j / prior-side precisions Lambda_j are K x K matrices --
the matrix structure is what lets the algorithm carry both the
lag-correlated prior Gamma (the analogue of their reduced-class prior
covariance Sigma~ = I + 11^T, eq. C.11) and the lag correlations of the
inputs themselves (a spin's K consecutive values are strongly correlated by
the dynamics) exactly, rather than through a diagonal approximation. The
output channel is the scalar Glauber likelihood P(y | h) = sigmoid(2 beta y h).

One AMP iteration (r = row index, all rows updated in parallel):

  channel:  V_rt   = sum_j x_tj^T C_rj x_tj
            omega_rt = sum_j w_hat_rj . x_tj - V_rt g_rt^{old}       (Onsager)
            g_rt   = d/d omega  log Z_out(y_rt, omega_rt, V_rt)
            dg_rt  = d^2/d omega^2 log Z_out(y_rt, omega_rt, V_rt)
  prior:    Lambda_rj = - sum_t dg_rt x_tj x_tj^T                     (K x K)
            gamma_rj  =   sum_t g_rt x_tj + Lambda_rj w_hat_rj        (K)
  posterior: C_rj     = (Sigma^{-1} + Lambda_rj)^{-1}
             w_hat_rj = C_rj gamma_rj

with Z_out(y, omega, V) = E_{h ~ N(omega, V)}[sigmoid(2 beta y h)] (computed by
Gauss-Hermite quadrature) and Sigma = coupling_scale^2 Gamma / N the
student's prior covariance. Self-couplings are known to be zero in the
teacher, which is encoded as a zero prior covariance for j = i.

Caveat: AMP's derivation and its state evolution assume a design with
independent entries. Here the inputs are the teacher's own spins: weakly
correlated across sites j (O(1/sqrt N) under SK scaling, which is fine),
but strongly correlated across lags within a block (handled exactly by the
K x K matrices above) and shared between consecutive samples t, t+1 (a
shifted window, not handled). Empirically (scripts/_amp_diagnose.py,
N=100, K=4, alpha=16): within-block lag correlations alone are harmless,
and neither is the window overlap (non-overlapping strided windows fail the
same way); what breaks plain AMP at beta=1 is cross-sample correlation from
the teacher's collective modes -- the sample Gram matrix's top eigenvalue
sits ~150x above its mean, vs ~9x for an iid +-1 design. Damping 0.5
diverges there, damping 0.8 converges and still beats MAP. Damping is
therefore on by default (with an adaptive increase if the iterates start
growing), and `map_estimate` gives an independent convex baseline.
"""
from dataclasses import dataclass, field

import numpy as np
import torch
import torch.nn.functional as F

from .config import DisorderConfig
from .simulate import build_gamma, rollout, sample_disorder


@dataclass
class StudentConfig:
    """Student's model of the teacher. None = matched to the teacher
    (the Bayes-optimal setting); set any field to study a mismatched
    Bayesian student."""

    beta: float | None = None
    gamma_kind: str | None = None
    gamma_param: float | None = None
    coupling_scale: float | None = None


@dataclass
class AMPConfig:
    max_iter: int = 200
    tol: float = 1e-6  # stop when ||w_new - w_old|| / ||w_old|| < tol
    damping: float = 0.8  # weight on the previous iterate, 0 = undamped
    # If the step size ||w_new - w_old|| grows for `patience` iterations in a
    # row, move damping halfway to 1 (capped at max_damping). See the caveat
    # in the module docstring: at low temperature the teacher's collective
    # modes give the design outlier singular values and undamped AMP diverges.
    adaptive_damping: bool = True
    patience: int = 5
    max_damping: float = 0.98
    n_quad: int = 48  # Gauss-Hermite points for the output channel
    device: str = "cpu"
    dtype: torch.dtype = torch.float64
    student: StudentConfig = field(default_factory=StudentConfig)


# ----------------------------------------------------------------------------
# Data: teacher trajectories -> (X, Y) design
# ----------------------------------------------------------------------------


def build_design(history, s):
    """history: (K, N) oldest-first initial context; s: (T, N) trajectory.
    Returns X: (T, N, K) with X[t, j, lag-1] = s_{t-lag, j} (J's lag
    convention, simulate.local_field), and Y = s: (T, N)."""
    k = history.shape[0]
    full = np.concatenate([history, s], axis=0)  # (K + T, N)
    t_steps = s.shape[0]
    x = np.stack([full[k - lag : k - lag + t_steps] for lag in range(1, k + 1)], axis=-1)
    return x, s


def teacher_data(cfg: DisorderConfig, n_sequences, t_steps, seed, j=None):
    """Draw a teacher (unless `j` is given) and n_sequences independent
    trajectories of length t_steps from it, each started from a uniformly
    random context. Returns (J, Gamma, X, Y) with X, Y stacked over
    sequences: X (n_sequences * t_steps, N, K), Y (n_sequences * t_steps, N)."""
    rng = np.random.default_rng(seed)
    if j is None:
        j, gamma = sample_disorder(cfg, rng)
    else:
        gamma = build_gamma(cfg.context_length, cfg.gamma_kind, cfg.gamma_param)
    xs, ys = [], []
    for _ in range(n_sequences):
        init = rng.choice([-1.0, 1.0], size=(cfg.context_length, cfg.n_spins))
        s, _ = rollout(j, cfg, rng, t_steps, init=init)
        x, y = build_design(init, s)
        xs.append(x)
        ys.append(y)
    return j, gamma, np.concatenate(xs), np.concatenate(ys)


