def predictive_nll(x, y, w_hat, c=None, beta=1.0, n_quad=48):
    """Mean per-spin NLL on (x, y) of the Bayesian predictive
    P(y | x) = E_{h ~ N(w_hat.x, x^T C x)} sigmoid(2 beta y h); plug-in if c is None.
    Pass the teacher's J (and c=None) to get the Bayes-optimal (teacher) NLL."""
    w_hat = torch.as_tensor(w_hat)
    dev, dt = w_hat.device, w_hat.dtype
    x = torch.as_tensor(x, device=dev, dtype=dt)
    y = torch.as_tensor(y, device=dev, dtype=dt).T
    t_steps, n, k = x.shape
    omega = w_hat.reshape(n, n * k) @ x.reshape(t_steps, n * k).T
    if c is None:
        return float(F.softplus(-2 * beta * y * omega).mean())
    xx = torch.einsum("tjk,tjl->tjkl", x, x).reshape(t_steps, n * k * k)
    v = torch.as_tensor(c, device=dev, dtype=dt).reshape(n, n * k * k) @ xx.T
    _, _, log_z = output_denoiser(y, omega, v, beta, _gauss_hermite(n_quad, dev, dt))
    return float(-log_z.mean())


def map_estimate(x, y, sigma, beta, max_iter=500, device="cpu", dtype=torch.float64):
    """MAP baseline: argmin_w sum_t softplus(-2 beta y_t h_t) + 1/2 sum_j w_j^T Sigma^{-1} w_j,
    all rows at once (the objective is separable over rows, so summing is
    fine). Parametrized as w_j = L u_j with Sigma = L L^T so Sigma^{-1} is
    never formed. Strictly convex -> unique, so L-BFGS is reliable."""
    x = torch.as_tensor(x, device=device, dtype=dtype)
    y = torch.as_tensor(y, device=device, dtype=dtype).T
    t_steps, n, k = x.shape
    sigma = torch.as_tensor(sigma, device=device, dtype=dtype)
    l = torch.linalg.cholesky(sigma + 1e-12 * torch.eye(k, device=device, dtype=dtype))
    mask = (1.0 - torch.eye(n, device=device, dtype=dtype))[..., None]
    x_flat = x.reshape(t_steps, n * k)
    u = torch.zeros(n, n, k, device=device, dtype=dtype, requires_grad=True)
    opt = torch.optim.LBFGS([u], max_iter=max_iter, tolerance_grad=1e-10, tolerance_change=1e-14,
                            history_size=50, line_search_fn="strong_wolfe")

    def closure():
        opt.zero_grad()
        w = mask * (u @ l.T)
        h = w.reshape(n, n * k) @ x_flat.T
        loss = F.softplus(-2 * beta * y * h).sum() + 0.5 * (mask * u**2).sum()
        loss.backward()
        return loss

    opt.step(closure)
    with torch.no_grad():
        return mask * (u @ l.T)
