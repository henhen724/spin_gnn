def _gauss_hermite(n, device, dtype):
    """Nodes/log-weights for E_{z ~ N(0,1)}[f(z)] ~= sum_k w_k f(z_k)."""
    z, w = np.polynomial.hermite_e.hermegauss(n)
    w = w / np.sqrt(2 * np.pi)
    return torch.tensor(z, device=device, dtype=dtype), torch.tensor(np.log(w), device=device, dtype=dtype)


def output_denoiser(y, omega, v, beta, quad):
    """Glauber channel P(y | h) = sigmoid(2 beta y h), h ~ N(omega, V).

    Returns (g, dg, log Z_out), elementwise over the broadcast shape:
      g  = d/d omega log Z_out = E_Q[h - omega] / V
      dg = d^2/d omega^2 log Z_out = (Var_Q[h] - V) / V^2
    where Q(h) ∝ P(y | h) N(h; omega, V) (eqs. C.9c-d, E.1b of Cornacchia
    et al. with k = 1). Writing h = omega + sqrt(V) z, the tilted moments of
    z are taken by quadrature in log space, so g = E_Q[z] / sqrt(V) and
    dg = (Var_Q[z] - 1) / V. For V -> 0 that difference cancels badly, so
    there we switch to the V = 0 limit (derivatives of log P(y | omega)).
    """
    z, logw = quad
    v_safe = v.clamp_min(1e-12)
    sv = v_safe.sqrt()
    h = omega[..., None] + sv[..., None] * z
    loglik = -F.softplus(-2 * beta * y[..., None] * h)  # log sigmoid(2 beta y h)
    logq = logw + loglik
    log_z = torch.logsumexp(logq, dim=-1)
    q = torch.exp(logq - log_z[..., None])
    mz = (q * z).sum(-1)
    vz = (q * z**2).sum(-1) - mz**2
    g = mz / sv
    dg = (vz - 1) / v_safe

    # V -> 0 limit: log P(y|omega) = log sigmoid(2 beta y omega)
    p = torch.sigmoid(2 * beta * y * omega)
    g0 = 2 * beta * y * (1 - p)
    dg0 = -((2 * beta) ** 2) * p * (1 - p)
    small = v < 1e-8
    return torch.where(small, g0, g), torch.where(small, dg0, dg), log_z


def prior_denoiser(gamma_vec, lam, sigma):
    """Gaussian prior N(0, Sigma), batched over leading dims (eqs. E.11b-c):
      C     = (Sigma^{-1} + Lambda)^{-1} = (I + Sigma Lambda)^{-1} Sigma
      w_hat = C gamma
    The second form never inverts Sigma, so it stays valid for the
    near-singular Gammas build_gamma can produce ("ones") and for the
    masked-out self-couplings (Sigma = 0 -> C = 0, w_hat = 0). I + Sigma Lambda
    is invertible whenever Lambda is PSD, which holds for any log-concave
    channel (Glauber included)."""
    k = sigma.shape[-1]
    eye = torch.eye(k, device=sigma.device, dtype=sigma.dtype)
    c = torch.linalg.solve(eye + sigma @ lam, sigma.expand_as(lam))
    c = 0.5 * (c + c.transpose(-1, -2))
    w = (c @ gamma_vec[..., None])[..., 0]
    return w, c


