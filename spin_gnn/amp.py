def _student_prior(cfg: DisorderConfig, student: StudentConfig):
    kind = student.gamma_kind if student.gamma_kind is not None else cfg.gamma_kind
    param = student.gamma_param if student.gamma_param is not None else cfg.gamma_param
    scale = student.coupling_scale if student.coupling_scale is not None else cfg.coupling_scale
    gamma = build_gamma(cfg.context_length, kind, param)
    return scale**2 * gamma / cfg.n_spins


def overlaps(w_hat, w_true):
    """K x K overlap matrices, averaged over rows (each O(1) under SK
    scaling): m = <sum_j w_hat_j w*_j^T>, q = <sum_j w_hat_j w_hat_j^T>,
    q* = <sum_j w*_j w*_j^T> (-> coupling_scale^2 Gamma as N -> inf)."""
    r = w_hat.shape[0]
    m = torch.einsum("rjk,rjl->kl", w_hat, w_true) / r
    q = torch.einsum("rjk,rjl->kl", w_hat, w_hat) / r
    qs = torch.einsum("rjk,rjl->kl", w_true, w_true) / r
    return m, q, qs


def run_amp(x, y, cfg: DisorderConfig, amp: AMPConfig = AMPConfig(), j_true=None, callback=None):
    """Run AMP on all N rows in parallel.

    x: (T, N, K) inputs (build_design), y: (T, N) outputs; numpy or torch.
    j_true: optional (N, N, K) teacher couplings, only used for per-iteration
    diagnostics (never by the algorithm itself).

    Returns dict with w_hat (N, N, K) [same layout as simulate's J],
    C (N, N, K, K) posterior covariances, and a per-iteration history.
    """
    dev, dt = amp.device, amp.dtype
    x = torch.as_tensor(x, device=dev, dtype=dt)
    y = torch.as_tensor(y, device=dev, dtype=dt).T.contiguous()  # (R, T), R = rows
    t_steps, n, k = x.shape
    beta = amp.student.beta if amp.student.beta is not None else cfg.beta

    sigma = torch.as_tensor(_student_prior(cfg, amp.student), device=dev, dtype=dt)
    mask = 1.0 - torch.eye(n, device=dev, dtype=dt)  # no self-couplings
    sigma_rj = mask[..., None, None] * sigma  # (R, N, K, K)

    xx = torch.einsum("tjk,tjl->tjkl", x, x).reshape(t_steps, n * k * k)  # for V and Lambda
    x_flat = x.reshape(t_steps, n * k)
    quad = _gauss_hermite(amp.n_quad, dev, dt)
    if j_true is not None:
        j_true = torch.as_tensor(j_true, device=dev, dtype=dt)

    # Uninformed initialization: posterior = prior.
    w_hat = torch.zeros(n, n, k, device=dev, dtype=dt)
    c = sigma_rj.clone()
    g = torch.zeros(n, t_steps, device=dev, dtype=dt)
    dg = torch.zeros_like(g)

    damping, n_growing, prev_delta = amp.damping, 0, float("inf")
    history = []
    for it in range(amp.max_iter):
        # --- channel ---
        v = c.reshape(n, n * k * k) @ xx.T  # (R, T): x_t^T C_r x_t summed over j
        omega = w_hat.reshape(n, n * k) @ x_flat.T - v * g
        g_new, dg_new, _ = output_denoiser(y, omega, v, beta, quad)
        if it == 0:
            g, dg = g_new, dg_new
        else:
            g = damping * g + (1 - damping) * g_new
            dg = damping * dg + (1 - damping) * dg_new

        # --- prior ---
        lam = (-dg @ xx).reshape(n, n, k, k)
        gam = (g @ x_flat).reshape(n, n, k) + (lam @ w_hat[..., None])[..., 0]

        # --- posterior ---
        w_new, c_new = prior_denoiser(gam, lam, sigma_rj)
        w_new = damping * w_hat + (1 - damping) * w_new
        c = damping * c + (1 - damping) * c_new

        delta = (w_new - w_hat).norm() / w_new.norm().clamp_min(1e-30)
        w_hat = w_new

        rec = {"iter": it, "delta": float(delta), "damping": damping}
        n_growing = n_growing + 1 if float(delta) > prev_delta else 0
        prev_delta = float(delta)
        if amp.adaptive_damping and n_growing >= amp.patience and damping < amp.max_damping:
            damping = min(amp.max_damping, 0.5 * (1 + damping))
            n_growing = 0
        if j_true is not None:
            rec["mse"] = float(((w_hat - j_true) ** 2).sum() / (j_true**2).sum())
            m, q, qs = overlaps(w_hat, j_true)
            rec["m_trace"] = float(torch.trace(m))
            rec["q_trace"] = float(torch.trace(q))
            rec["qs_trace"] = float(torch.trace(qs))
        history.append(rec)
        if callback is not None:
            callback(rec)
        if not torch.isfinite(delta):
            raise FloatingPointError(f"AMP diverged at iteration {it}")
        if it > 0 and delta < amp.tol:
            break

    return {"w_hat": w_hat, "C": c, "history": history, "beta": beta, "sigma": sigma}


